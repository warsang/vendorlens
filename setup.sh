#!/usr/bin/env bash
# VendorLens interactive setup — writes .env (gitignored, never committed).
# Run: ./setup.sh   (or: bash setup.sh)
set -euo pipefail

ENV_FILE=".env"
echo "VendorLens setup — keys go into .env (gitignored). Leave blank to skip."
echo

ask() { # $1 = var name, $2 = prompt
  local val=""
  read -r -p "$2: " val
  printf '%s=%s\n' "$1" "$val"
}

{
  echo "# Generated by ./setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — DO NOT COMMIT"
  echo
  echo "### neatlogs observability (Project API key, the top key in Settings)"
  ask NEATLOGS_API_KEY "NEATLOGS_API_KEY (Enter to skip)"
  echo
  echo "### Crustdata enrichment (5,000 credits, promo NEATLOGS-OCT2026)"
  ask CRUSTDATA_API_KEY "CRUSTDATA_API_KEY (Enter to skip)"
  echo
  echo "### LLM for planning (pick one)"
  echo "  1) Hackathon LiteLLM shared key (from check-in email / Discord)"
  echo "  2) Local Ollama (http://localhost:11434/v1)"
  echo "  3) Skip — use --no-llm (live tools, deterministic plan)"
  read -r -p "Choice [1/2/3]: " choice
  case "$choice" in
    1)
      ask LITELLM_API_BASE "LITELLM_API_BASE (e.g. https://.../v1)"
      ask LITELLM_API_KEY "LITELLM_API_KEY"
      ask LITELLM_MODEL "LITELLM_MODEL (e.g. nova-micro)"
      ;;
    2)
      echo "LITELLM_API_BASE=http://localhost:11434/v1"
      ask LITELLM_MODEL "Ollama model name (e.g. llama3.1:8b)"
      echo "LITELLM_API_KEY=ollama"
      ;;
    *)
      echo "# No LLM configured — run with --no-llm or --demo"
      ;;
  esac
} > "$ENV_FILE"

chmod 600 "$ENV_FILE"
echo
echo "Wrote $ENV_FILE (mode 600, gitignored). Verify with: grep -c . $ENV_FILE lines set."
echo "Test:  python -m vendorlens example.com --no-llm"
